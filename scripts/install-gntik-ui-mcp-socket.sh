#!/usr/bin/env bash
# NEW-129: install the root-owned, fixed-command gntik-ui MCP socket on the scan worker.
#
# The scan worker (scan-runner) never gets Docker access. Instead systemd listens on
# /run/gntik-ui-mcp/mcp.sock (root:scan-runner 0660) and, per connection (Accept=yes),
# starts gntik-ui-mcp@<instance>.service as root, which runs exactly one command:
#   docker run -i --rm ... <image>@sha256:<digest> --stdio
# with the connection as its stdin/stdout. The image is pinned by digest here, in the
# reviewed unit file; the client cannot choose the command, image, flags or daemon.
#
# This script is the single source of the unit files (heredocs below).
#
# Usage (operator, on the worker):
#   sudo scripts/install-gntik-ui-mcp-socket.sh \
#     --manifest /etc/engineering-control/projects.d/falcone.yaml
#   sudo scripts/install-gntik-ui-mcp-socket.sh --image ghcr.io/gntik-ai/gntik-ui-mcp@sha256:<64 hex>
#   scripts/install-gntik-ui-mcp-socket.sh --manifest <file> --dry-run   # print the units only
#   sudo scripts/install-gntik-ui-mcp-socket.sh --uninstall
#
# Idempotent: files are rewritten only when their content changes; re-running with a new
# digest pre-pulls it, updates the service template and restarts the socket.
set -euo pipefail
umask 022

readonly SOCKET_PATH=/run/gntik-ui-mcp/mcp.sock
readonly SOCKET_DIR=/run/gntik-ui-mcp
readonly SOCKET_GROUP=scan-runner
readonly SOCKET_UNIT=gntik-ui-mcp.socket
readonly SERVICE_UNIT=gntik-ui-mcp@.service
readonly UNIT_DIR=/etc/systemd/system
readonly TMPFILES_CONF=/etc/tmpfiles.d/gntik-ui-mcp.conf
readonly STATE_DIR=/var/lib/gntik-ui-mcp
readonly DOCKER_CONFIG_DIR=/var/lib/gntik-ui-mcp/docker-config
readonly DOCKER_HOST_SOCKET=unix:///var/run/docker.sock
# The service outlives the client's whole session: ui_kit DEFAULT_DEADLINE_SECONDS (180)
# plus its shutdown allowance (10) plus a margin (tests/test_install_gntik_ui_mcp_socket.py).
readonly SERVICE_RUNTIME_MAX_SEC=210
readonly SCAN_WORKER_UNIT=engineering-worker@scan.service
readonly IMAGE_RE='^[a-z0-9]([a-z0-9.-]*[a-z0-9])?(:[0-9]{1,5})?(/[a-z0-9][a-z0-9._-]*)+$'
readonly DIGEST_RE='^sha256:[a-f0-9]{64}$'
# Not readonly only so the tests can source this file and substitute an unprivileged owner
# and a fake CLI; nothing reads them from the environment.
DOCKER=/usr/bin/docker
ROOT_UID=0
ROOT_GID=0

usage() {
  sed -n '13,18p' "$0" | sed 's/^# \{0,1\}//'
  exit 2
}

die() {
  printf 'install-gntik-ui-mcp-socket: %s\n' "$*" >&2
  exit 1
}

MANIFEST=""
IMAGE_ARG=""
DRY_RUN=0
UNINSTALL=0
REFERENCE=""

# -- the pinned image reference ----------------------------------------------------------

manifest_value() {
  # The `ui_migration.mcp.<key>` scalar of a project manifest (fixed two-space layout).
  awk -v key="$1" '
    /^ui_migration:/ { ui = 1; next }
    ui && /^[^ #]/ { ui = 0; mcp = 0 }
    ui && /^  mcp:/ { mcp = 1; next }
    mcp && /^  [^ ]/ { mcp = 0 }
    mcp && $1 == key ":" { value = $2; gsub(/["\047]/, "", value); print value; exit }
  ' "$2"
}

resolve_reference() {
  local image digest socket
  if [[ -n "$MANIFEST" && -n "$IMAGE_ARG" ]]; then
    die "give either --manifest or --image, not both"
  elif [[ -n "$MANIFEST" ]]; then
    [[ -f "$MANIFEST" && -r "$MANIFEST" ]] || die "cannot read manifest $MANIFEST"
    image=$(manifest_value image "$MANIFEST")
    digest=$(manifest_value digest "$MANIFEST")
    socket=$(manifest_value socket "$MANIFEST")
    [[ -n "$image" && -n "$digest" ]] || die "no ui_migration.mcp image/digest in $MANIFEST"
    if [[ -n "$socket" && "$socket" != "$SOCKET_PATH" ]]; then
      die "the manifest socket $socket is not $SOCKET_PATH"
    fi
  elif [[ -n "$IMAGE_ARG" ]]; then
    [[ "$IMAGE_ARG" == *@* ]] || die "refusing $IMAGE_ARG: a tag is not a pin (use <image>@sha256:<digest>)"
    image=${IMAGE_ARG%@*}
    digest=${IMAGE_ARG##*@}
  else
    die "give --manifest <project manifest> or --image <image>@sha256:<digest>"
  fi
  [[ "$image" =~ $IMAGE_RE ]] || die "refusing image $image: not a tagless repository reference"
  [[ "$digest" =~ $DIGEST_RE ]] || die "refusing digest $digest: not sha256:<64 hex>"
  REFERENCE="$image@$digest"
}

# -- the unit files (single source) ------------------------------------------------------

render_socket_unit() {
  cat <<EOF
# Generated by scripts/install-gntik-ui-mcp-socket.sh (NEW-129). Do not edit by hand.
[Unit]
Description=gntik-ui MCP socket for the Hermes scan worker (NEW-129)
Documentation=file:///opt/engineering-control/source/scripts/install-gntik-ui-mcp-socket.sh

[Socket]
# systemd creates missing parents as root:root with DirectoryMode, so the group could not
# traverse them; ${TMPFILES_CONF} owns ${SOCKET_DIR} (root:${SOCKET_GROUP} 0750) instead.
ExecStartPre=/usr/bin/systemd-tmpfiles --create ${TMPFILES_CONF}
ListenStream=${SOCKET_PATH}
Accept=yes
MaxConnections=4
SocketUser=root
SocketGroup=${SOCKET_GROUP}
SocketMode=0660
DirectoryMode=0750
RemoveOnStop=yes

[Install]
WantedBy=sockets.target
EOF
}

render_service_unit() {
  # %i of an Accept=yes AF_UNIX instance is "<n>-<pid>-<uid>" (or "<n>-unknown"): digits
  # and hyphens only, so "gntik-ui-mcp-%i" is a valid, per-connection container name.
  # (%I would unescape "-" to "/", hence %i.)
  cat <<EOF
# Generated by scripts/install-gntik-ui-mcp-socket.sh (NEW-129). Do not edit by hand.
[Unit]
Description=gntik-ui MCP stdio server for one scan-worker connection (NEW-129)
Requires=docker.service
After=docker.service
CollectMode=inactive-or-failed

[Service]
Type=simple
StandardInput=socket
StandardOutput=socket
StandardError=journal
# An empty, root-owned config directory and the explicit local daemon: no user context,
# credential helper or DOCKER_HOST can redirect the CLI.
Environment=DOCKER_CONFIG=${DOCKER_CONFIG_DIR} DOCKER_CONTEXT=default DOCKER_HOST=${DOCKER_HOST_SOCKET}
ExecStart=${DOCKER} run -i --rm --name gntik-ui-mcp-%i --pull never --network none --read-only --cap-drop ALL --security-opt no-new-privileges --memory 512m --pids-limit 256 ${REFERENCE} --stdio
ExecStopPost=-${DOCKER} rm -f gntik-ui-mcp-%i
RuntimeMaxSec=${SERVICE_RUNTIME_MAX_SEC}
TimeoutStopSec=15
# Hardening of the Docker CLI process (root, no capabilities: it owns no privilege beyond
# connecting to the root-owned /var/run/docker.sock, a filesystem AF_UNIX socket).
UMask=0077
NoNewPrivileges=yes
CapabilityBoundingSet=
AmbientCapabilities=
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
PrivateNetwork=yes
IPAddressDeny=any
RestrictAddressFamilies=AF_UNIX
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
ProtectProc=invisible
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
SystemCallArchitectures=native
SystemCallFilter=@system-service
EOF
}

render_tmpfiles() {
  cat <<EOF
# Generated by scripts/install-gntik-ui-mcp-socket.sh (NEW-129).
d ${SOCKET_DIR} 0750 root ${SOCKET_GROUP} -
EOF
}

# -- the smoke test (initialize, tools/list) ---------------------------------------------

read -r -d '' SMOKE_PY <<'PY' || true
import json, socket, sys

path = sys.argv[1]
connection = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
connection.settimeout(90)
connection.connect(path)
stream = connection.makefile("rwb")


def rpc(request_id, method, params):
    message = {"jsonrpc": "2.0", "id": request_id, "method": method, "params": params}
    stream.write(json.dumps(message).encode() + b"\n")
    stream.flush()
    while True:
        line = stream.readline(4 * 1024 * 1024 + 1)
        if not line:
            raise SystemExit("GNTIK_UI_MCP_SOCKET_SMOKE_FAIL: the server closed the session")
        reply = json.loads(line)
        if isinstance(reply, dict) and reply.get("id") == request_id:
            if "result" not in reply:
                raise SystemExit(f"GNTIK_UI_MCP_SOCKET_SMOKE_FAIL: {method} failed")
            return reply["result"]


init = rpc(1, "initialize", {
    "protocolVersion": "2025-06-18",
    "capabilities": {},
    "clientInfo": {"name": "gntik-ui-mcp-smoke", "version": "1"},
})
stream.write(b'{"jsonrpc":"2.0","method":"notifications/initialized"}\n')
stream.flush()
tools = rpc(2, "tools/list", {}).get("tools", [])
connection.close()
print(json.dumps({
    "status": "GNTIK_UI_MCP_SOCKET_SMOKE_PASS",
    "server": init.get("serverInfo", {}),
    "protocol": init.get("protocolVersion"),
    "tools": len(tools),
}, sort_keys=True))
PY

# -- helpers -----------------------------------------------------------------------------

CHANGED=()

verify_root_directory() {
  # verify_root_directory <path>: a real directory (stat never follows a symlink) owned by
  # root that neither group nor others can write, so no one else can swap its entries.
  local owner mode kind
  read -r owner mode kind < <(stat -c '%u %a %F' -- "$1") || die "cannot stat $1"
  [[ "$owner" == "$ROOT_UID" && "$kind" == directory ]] || die "$1 is not a root-owned directory"
  ((!(8#$mode & 8#022))) || die "$1 is writable by group or others"
}

verify_root_path() {
  # verify_root_path <path> <mode> <type>: exactly root:root, <mode>, <type>; no symlink.
  local path=$1 expected actual
  expected="$ROOT_UID:$ROOT_GID ${2#0} $3"
  actual=$(stat -c '%u:%g %a %F' -- "$path") || die "cannot stat $path"
  [[ "$actual" == "$expected" ]] || die "$path is $actual, expected $expected"
}

ensure_root_dir() {
  # ensure_root_dir <path> <mode>: a symlink or non-directory at <path> is removed (never
  # followed) and a root-owned directory is (re)created; ownership and mode are repaired.
  local path=$1 mode=$2
  verify_root_directory "$(dirname -- "$path")"
  if [[ -L "$path" || (-e "$path" && ! -d "$path") ]]; then
    rm -f -- "$path"
  fi
  [[ -d "$path" ]] || mkdir -m "$mode" -- "$path"
  chown -h "$ROOT_UID:$ROOT_GID" -- "$path"
  [[ ! -L "$path" ]] || die "$path became a symlink"
  chmod "$mode" -- "$path"
  verify_root_path "$path" "$mode" directory
}

install_file() {
  # install_file <path> <mode> <content>: ALWAYS rewritten as root:root <mode> through a
  # root-owned temporary file in the same root-owned directory, renamed over the target
  # with mv -T: rename(2) replaces a symlink or a foreign-owned file, never follows it.
  local path=$1 mode=$2 content=$3 temporary same=0
  verify_root_directory "$(dirname -- "$path")"
  if [[ -f "$path" && ! -L "$path" ]] && cmp -s <(printf '%s\n' "$content") "$path"; then
    same=1
  fi
  temporary=$(mktemp -- "${path}.XXXXXX")
  printf '%s\n' "$content" >"$temporary"
  chown "$ROOT_UID:$ROOT_GID" -- "$temporary"
  chmod "$mode" -- "$temporary"
  mv -fT -- "$temporary" "$path"
  verify_root_path "$path" "$mode" "regular file"
  ((same)) || CHANGED+=("$path")
}

docker_service() {
  # The service's exact Docker environment: none of the operator's context, config,
  # DOCKER_HOST or credential helpers can point these commands at another daemon.
  env -i PATH=/usr/bin:/bin DOCKER_CONFIG="$DOCKER_CONFIG_DIR" DOCKER_CONTEXT=default \
    DOCKER_HOST="$DOCKER_HOST_SOCKET" "$DOCKER" "$@"
}

pull_image() {
  # Pre-pull by digest, then prove the local daemon holds exactly that digest.
  local digests
  docker_service pull --quiet "$REFERENCE" >/dev/null || die "pulling $REFERENCE failed"
  digests=$(docker_service image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' \
    "$REFERENCE") || die "$REFERENCE is not present on the local daemon"
  grep -Fqx -- "$REFERENCE" <<<"$digests" || die "the local image does not carry $REFERENCE"
}

uninstall() {
  systemctl disable --now "$SOCKET_UNIT" 2>/dev/null || true
  systemctl stop 'gntik-ui-mcp@*.service' 2>/dev/null || true
  rm -f "$UNIT_DIR/$SOCKET_UNIT" "$UNIT_DIR/$SERVICE_UNIT" "$TMPFILES_CONF"
  systemctl daemon-reload
  systemctl reset-failed 'gntik-ui-mcp@*.service' 2>/dev/null || true
  rm -f "$SOCKET_PATH"
  rmdir "$SOCKET_DIR" 2>/dev/null || true
  rmdir "$DOCKER_CONFIG_DIR" "$STATE_DIR" 2>/dev/null || true
  printf 'gntik-ui MCP socket removed (the pulled image is kept; remove it with docker rmi).\n'
  printf 'Set ui_migration.mcp.socket aside in the manifest or the scan step reports BLOCKED.\n'
}

# -- main --------------------------------------------------------------------------------

main() {
while (($#)); do
  case "$1" in
    --manifest) MANIFEST=${2:?--manifest needs a file}; shift 2 ;;
    --image) IMAGE_ARG=${2:?--image needs a reference}; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --uninstall) UNINSTALL=1; shift ;;
    -h | --help) usage ;;
    *) die "unknown argument: $1" ;;
  esac
done
if ((UNINSTALL)); then
  ((DRY_RUN)) && die "--dry-run and --uninstall are exclusive"
  [[ $EUID -eq 0 ]] || die "run as root (sudo)"
  uninstall
  exit 0
fi

resolve_reference
SOCKET_CONTENT=$(render_socket_unit)
SERVICE_CONTENT=$(render_service_unit)
TMPFILES_CONTENT=$(render_tmpfiles)

if ((DRY_RUN)); then
  printf '# image: %s\n' "$REFERENCE"
  printf '# ---- %s\n%s\n' "$UNIT_DIR/$SOCKET_UNIT" "$SOCKET_CONTENT"
  printf '# ---- %s\n%s\n' "$UNIT_DIR/$SERVICE_UNIT" "$SERVICE_CONTENT"
  printf '# ---- %s\n%s\n' "$TMPFILES_CONF" "$TMPFILES_CONTENT"
  printf '# no worker drop-in: %s connects through its read-only /run (see the summary).\n' \
    "$SCAN_WORKER_UNIT"
  exit 0
fi

[[ $EUID -eq 0 ]] || die "run as root (sudo), or use --dry-run"
getent group "$SOCKET_GROUP" >/dev/null || die "group $SOCKET_GROUP does not exist"
getent passwd "$SOCKET_GROUP" >/dev/null || die "user $SOCKET_GROUP does not exist"
[[ -x "$DOCKER" ]] || die "$DOCKER is missing"
verify_root_path "$DOCKER" 0755 "regular file"
systemctl is-active --quiet docker.service || die "docker.service is not active"

ensure_root_dir "$STATE_DIR" 0700
ensure_root_dir "$DOCKER_CONFIG_DIR" 0700
if [[ -n "$(ls -A "$DOCKER_CONFIG_DIR")" ]]; then
  die "$DOCKER_CONFIG_DIR must stay empty (found: $(ls -A "$DOCKER_CONFIG_DIR" | tr '\n' ' '))"
fi

printf '==> pre-pulling %s with the service Docker environment\n' "$REFERENCE"
pull_image

WAS_ACTIVE=0
systemctl is-active --quiet "$SOCKET_UNIT" && WAS_ACTIVE=1
install_file "$TMPFILES_CONF" 0644 "$TMPFILES_CONTENT"
install_file "$UNIT_DIR/$SERVICE_UNIT" 0644 "$SERVICE_CONTENT"
install_file "$UNIT_DIR/$SOCKET_UNIT" 0644 "$SOCKET_CONTENT"
# Reload only once every generated path is verified root:root and not g/o-writable.
for generated in "$TMPFILES_CONF" "$UNIT_DIR/$SERVICE_UNIT" "$UNIT_DIR/$SOCKET_UNIT"; do
  verify_root_path "$generated" 0644 "regular file"
done
verify_root_path "$STATE_DIR" 0700 directory
verify_root_path "$DOCKER_CONFIG_DIR" 0700 directory
systemd-tmpfiles --create "$TMPFILES_CONF"
systemctl daemon-reload
systemctl enable --now "$SOCKET_UNIT"
if ((${#CHANGED[@]} && WAS_ACTIVE)); then
  systemctl restart "$SOCKET_UNIT"
fi

# -- verification ------------------------------------------------------------------------

directory_mode=$(stat -c '%U:%G %a' "$SOCKET_DIR")
socket_mode=$(stat -c '%U:%G %a %F' "$SOCKET_PATH")
[[ "$directory_mode" == "root:$SOCKET_GROUP 750" ]] || die "$SOCKET_DIR is $directory_mode"
[[ "$socket_mode" == "root:$SOCKET_GROUP 660 socket" ]] || die "$SOCKET_PATH is $socket_mode"
runuser -u "$SOCKET_GROUP" -- test -x "$SOCKET_DIR" || die "$SOCKET_GROUP cannot traverse $SOCKET_DIR"

printf '==> smoke test as %s\n' "$SOCKET_GROUP"
SMOKE=$(cd / && runuser -u "$SOCKET_GROUP" -- /usr/bin/python3 - "$SOCKET_PATH" <<<"$SMOKE_PY")
printf '%s\n' "$SMOKE"

# No worker drop-in: connect() needs write permission on the socket inode (granted by the
# group), and a read-only mount (ProtectSystem=strict) refuses only filesystem changes, not
# connect(); PrivateTmp/ProtectHome do not cover /run. The worker's mount namespace shares
# the host's /run tmpfs, so a socket created after the worker started is visible. Prove it
# inside the running worker's own namespace when it is active.
WORKER_SMOKE="skipped (${SCAN_WORKER_UNIT} not active)"
worker_pid=$(systemctl show -p MainPID --value "$SCAN_WORKER_UNIT" 2>/dev/null || echo 0)
if [[ -n "$worker_pid" && "$worker_pid" != 0 ]]; then
  printf '==> smoke test inside the %s mount namespace\n' "$SCAN_WORKER_UNIT"
  WORKER_SMOKE=$(cd / && nsenter --target "$worker_pid" --mount \
    --setuid "$(id -u "$SOCKET_GROUP")" --setgid "$(id -g "$SOCKET_GROUP")" \
    -- /usr/bin/python3 - "$SOCKET_PATH" <<<"$SMOKE_PY") \
    || die "the scan worker namespace cannot reach $SOCKET_PATH: a drop-in is needed"
  printf '%s\n' "$WORKER_SMOKE"
fi

cat <<EOF

gntik-ui MCP socket installed (NEW-129)
  image:           $REFERENCE
  socket:          $SOCKET_PATH ($socket_mode)
  directory:       $SOCKET_DIR ($directory_mode)
  units:           $UNIT_DIR/$SOCKET_UNIT, $UNIT_DIR/$SERVICE_UNIT, $TMPFILES_CONF
  changed files:   ${CHANGED[*]:-none}
  socket state:    $(systemctl is-active "$SOCKET_UNIT")
  smoke (runuser): $SMOKE
  smoke (worker):  $WORKER_SMOKE
  worker drop-in:  none needed ($SCAN_WORKER_UNIT connects through its read-only /run)
EOF
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
