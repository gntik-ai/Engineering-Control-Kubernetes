def _entry(
    category: str,
    action: str,
    label: str,
    *,
    available: bool,
    effect: str,
    fields: list[dict[str, Any]] | None = None,
    blocker: str | None = None,
    href: str | None = None,
) -> dict[str, Any]:
    return {
        "category": category,
        "action": action,
        "label": label,
        "status": "AVAILABLE" if available else "DISABLED",
        "effect": effect,
        "fields": fields or [],
        "blockers": [] if available else [blocker or "TYPED_APPLICATION_METHOD_NOT_IMPLEMENTED"],
        "href": href,
    }


